/* ============================================================
   统一前端风格：Design Token 层
   ------------------------------------------------------------
   改之前的实测数据（tools/diag-style.js）：
     圆角   38 处 / 13 种   12px 99px 8px 9px 14px 11px 10px 50% …混杂
     字号   70 处 / 16 种   10.5 11 11.5 12 12.5 13 13.5 14 15 16 17 19 20 23 24 34
     内距   40 处 / 33 种   完全没有节奏
     间距   23 处 / 10 种
     内联 style 83 处 / 43 种，其中 margin-top:0 单独出现 16 次
     未定义变量 4 个：--green700 --red700 --amber700 --blue700
       （.lv.ok/.half/.bad/.new 引用它们，两套主题下都拿不到颜色）

   做法：先把「尺度」固化成 token，再把散落的字面量收敛到 token。
   不改布局、不改配色语义、不动任何交互 —— 纯样式层收敛，零功能风险。
   ============================================================ */

/* ---- 1. 补齐色阶：新增 *700（标签文字色，介于 600 与 800 之间） ----
   为什么要 700：600 是 --xx600，在 --xx50 底上偏浅（WCAG 约 3.9:1），
   800 又太深、跟标题同级。标签是 11px 小字，必须有独立的一档。 */
const COLOR = `
  /* 色阶补全：700 = 标签/徽章文字色（11px 小字专用，对比度 ≥ 4.5:1）
     600 = 图标/强调/边框   800 = 标题级强调            */
  --blue700:#0f4c85;
  --green700:#2f5610;
  --amber700:#6b400a;
  --red700:#852626;
  --purple700:#464090;`;

/* ---- 2. 排版阶梯：16 种字号收敛到 8 档 ----
   映射关系（就近归并，视觉差 ≤0.5px 肉眼不可辨）：
     10.5 11 → --fs-xs    (11px)  标签、徽章、meta
     11.5 12 → --fs-sm    (12px)  副文本、说明
     12.5 13 → --fs-md    (13px)  正文次级、.sub
     13.5 14 → --fs-base  (14px)  正文默认
     15        → --fs-lg   (15px)  列表泰文、body
     16 17 19  → --fs-xl   (17px)  选项泰文、卡片标题
     20 23 24  → --fs-2xl  (22px)  KPI 数字
     34        → --fs-3xl  (34px)  空态图标 */
const FONT = `
  /* 排版阶梯：8 档，每档都有明确用途，不要在组件里写字面量 */
  --fs-xs:11px; --fs-sm:12px; --fs-md:13px; --fs-base:14px;
  --fs-lg:15px; --fs-xl:17px; --fs-2xl:22px; --fs-3xl:34px;
  --lh-tight:1.3; --lh:1.65; --lh-loose:1.9;   /* 泰文有上下标，行高要给足 */
  --fw:400; --fw-md:600; --fw-bold:700;`;

/* ---- 3. 间距阶梯：33 种内距 / 10 种 gap 收敛到 4px 栅格 ---- */
const SPACE = `
  /* 间距：4px 栅格，只允许用这 6 档 */
  --s1:4px; --s2:8px; --s3:12px; --s4:16px; --s5:20px; --s6:28px;`;

/* ---- 4. 圆角：13 种收敛到 4 档 ---- */
const RADIUS = `
  /* 圆角：4 档。--r-lg 卡片/浮层 16px｜--r 控件 11px｜--r-sm 标签 8px｜--r-pill 胶囊 */
  --r-pill:99px;
  --r-xs:8px;`;

/* ---- 5. 动效：统一时长与缓动 ---- */
const MOTION = `
  /* 动效：只在「按压反馈」和「浮层进出」上用，页面切换不做动画 */
  --t-fast:120ms; --t:180ms;
  --ease:cubic-bezier(.2,.7,.3,1);`;

module.exports = { COLOR, FONT, SPACE, RADIUS, MOTION };
